-- Demo target schema `app` (docs/database_schema.md §4 + §7). FIXTURE, not a migration.
-- Every table exercises a specific engine behaviour (see the comment on each table).
-- Money is integer cents. No floating-point columns except the pgvector embedding.
-- Re-runnable: drops every demo object first (objects only; the schema and its grants stay).

SET client_min_messages = warning;
CREATE SCHEMA IF NOT EXISTS app;

-- derived objects first (they depend on the base tables)
DROP TABLE IF EXISTS app.customer_segment CASCADE;
DROP MATERIALIZED VIEW IF EXISTS app.daily_revenue CASCADE;
DROP MATERIALIZED VIEW IF EXISTS app.customer_ltv CASCADE;

DROP TABLE IF EXISTS app.marketing_event_log CASCADE;
DROP TABLE IF EXISTS app.customer_profile_cache CASCADE;
DROP TABLE IF EXISTS app.document_embedding CASCADE;
DROP TABLE IF EXISTS app.document CASCADE;
DROP TABLE IF EXISTS app.ticket_message CASCADE;
DROP TABLE IF EXISTS app.support_ticket CASCADE;
DROP TABLE IF EXISTS app.payment CASCADE;
DROP TABLE IF EXISTS app.shipment CASCADE;
DROP TABLE IF EXISTS app.order_line CASCADE;
DROP TABLE IF EXISTS app.purchase_order CASCADE;
DROP TABLE IF EXISTS app.product CASCADE;
DROP TABLE IF EXISTS app.loyalty_account CASCADE;
DROP TABLE IF EXISTS app.customer_address CASCADE;
DROP TABLE IF EXISTS app.customer CASCADE;

-- subject root; self-reference (other subjects) via referrer_id ON DELETE SET NULL
CREATE TABLE app.customer (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    text        NOT NULL,
    email        text        NOT NULL UNIQUE,
    phone        text,
    referrer_id  bigint REFERENCES app.customer (id) ON DELETE SET NULL,
    created_at   timestamptz NOT NULL,
    CONSTRAINT customer_no_self_referral CHECK (referrer_id IS NULL OR referrer_id <> id)
);
CREATE INDEX ix_customer_referrer_id ON app.customer (referrer_id);

-- EXPECT_CASCADE
CREATE TABLE app.customer_address (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint NOT NULL REFERENCES app.customer (id) ON DELETE CASCADE,
    line1        text   NOT NULL,
    city         text   NOT NULL,
    postal_code  text   NOT NULL,
    country      text   NOT NULL
);
CREATE INDEX ix_customer_address_customer_id ON app.customer_address (customer_id);

-- PK = FK (1:1), NO ACTION
CREATE TABLE app.loyalty_account (
    customer_id  bigint PRIMARY KEY REFERENCES app.customer (id) ON DELETE NO ACTION,
    points       bigint NOT NULL DEFAULT 0 CHECK (points >= 0),
    tier         text   NOT NULL CHECK (tier IN ('BRONZE', 'SILVER', 'GOLD')),
    joined_at    timestamptz NOT NULL
);

-- upstream reference data: must NOT be traversed
CREATE TABLE app.product (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text   NOT NULL UNIQUE,
    name         text   NOT NULL,
    price_cents  bigint NOT NULL CHECK (price_cents >= 0)
);

-- retention policy ANONYMIZE (tax records); nullable RESTRICT reference to the subject
CREATE TABLE app.purchase_order (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       bigint REFERENCES app.customer (id) ON DELETE RESTRICT,
    ordered_at        timestamptz NOT NULL,
    status            text   NOT NULL CHECK (status IN ('PLACED', 'PAID', 'SHIPPED', 'CANCELLED')),
    shipping_name     text,
    shipping_address  text,
    total_cents       bigint NOT NULL CHECK (total_cents >= 0)
);
CREATE INDEX ix_purchase_order_customer_id ON app.purchase_order (customer_id);

-- composite PK; CASCADE from purchase_order (conflicts with a retained order)
CREATE TABLE app.order_line (
    order_id          bigint  NOT NULL REFERENCES app.purchase_order (id) ON DELETE CASCADE,
    line_no           integer NOT NULL CHECK (line_no >= 1),
    product_id        bigint  NOT NULL REFERENCES app.product (id),
    quantity          integer NOT NULL CHECK (quantity >= 1),
    unit_price_cents  bigint  NOT NULL CHECK (unit_price_cents >= 0),
    PRIMARY KEY (order_id, line_no)
);
CREATE INDEX ix_order_line_order_id ON app.order_line (order_id);
CREATE INDEX ix_order_line_product_id ON app.order_line (product_id);

-- composite FK (order_id, line_no) -> order_line, NO ACTION
CREATE TABLE app.shipment (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       bigint  NOT NULL,
    line_no        integer NOT NULL,
    carrier        text    NOT NULL,
    tracking_code  text    NOT NULL,
    shipped_at     timestamptz NOT NULL,
    CONSTRAINT shipment_order_line_fkey FOREIGN KEY (order_id, line_no)
        REFERENCES app.order_line (order_id, line_no) ON DELETE NO ACTION
);
CREATE INDEX ix_shipment_order_id_line_no ON app.shipment (order_id, line_no);

-- multi-hop (customer -> purchase_order -> payment), NO ACTION
CREATE TABLE app.payment (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      bigint NOT NULL REFERENCES app.purchase_order (id) ON DELETE NO ACTION,
    amount_cents  bigint NOT NULL CHECK (amount_cents >= 0),
    method        text   NOT NULL CHECK (method IN ('CARD', 'BANK_TRANSFER', 'VOUCHER')),
    paid_at       timestamptz NOT NULL
);
CREATE INDEX ix_payment_order_id ON app.payment (order_id);

CREATE TABLE app.support_ticket (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint REFERENCES app.customer (id) ON DELETE SET NULL,
    subject      text   NOT NULL,
    status       text   NOT NULL CHECK (status IN ('OPEN', 'PENDING', 'CLOSED')),
    opened_at    timestamptz NOT NULL
);
CREATE INDEX ix_support_ticket_customer_id ON app.support_ticket (customer_id);

-- shared record: another customer can author a message on the subject's ticket
CREATE TABLE app.ticket_message (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id           bigint NOT NULL REFERENCES app.support_ticket (id) ON DELETE CASCADE,
    author_customer_id  bigint REFERENCES app.customer (id) ON DELETE NO ACTION,
    body                text   NOT NULL,
    sent_at             timestamptz NOT NULL
);
CREATE INDEX ix_ticket_message_ticket_id ON app.ticket_message (ticket_id);
CREATE INDEX ix_ticket_message_author_customer_id ON app.ticket_message (author_customer_id);

-- free text that contains the customer's name and email (CR lead-1 §5)
CREATE TABLE app.document (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint NOT NULL REFERENCES app.customer (id) ON DELETE CASCADE,
    title        text   NOT NULL,
    body         text   NOT NULL,
    created_at   timestamptz NOT NULL
);
CREATE INDEX ix_document_customer_id ON app.document (customer_id);

-- EMBEDDING_TABLE: no declared FK; registered mapping source_document_id -> app.document.id
CREATE TABLE app.document_embedding (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_document_id  bigint NOT NULL,
    model               text   NOT NULL,
    embedding           vector(384) NOT NULL
);
CREATE INDEX ix_document_embedding_source_document_id ON app.document_embedding (source_document_id);

-- CACHE: no FK; keyed by customer_id; payload copies name/email (registered CACHE artifact)
CREATE TABLE app.customer_profile_cache (
    customer_id   bigint PRIMARY KEY,
    payload       jsonb  NOT NULL,
    refreshed_at  timestamptz NOT NULL
);

-- hidden copy: NO primary key, NO foreign key; only inference or the residual scan find it
CREATE TABLE app.marketing_event_log (
    email        text NOT NULL,
    event        text NOT NULL CHECK (event IN ('NEWSLETTER_OPEN', 'LINK_CLICK', 'UNSUBSCRIBE', 'CAMPAIGN_SENT')),
    occurred_at  timestamptz NOT NULL
);
CREATE INDEX ix_marketing_event_log_email ON app.marketing_event_log (email);
